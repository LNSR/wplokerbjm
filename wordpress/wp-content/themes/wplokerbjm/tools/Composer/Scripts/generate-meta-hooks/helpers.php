/**
 * Run a WP-CLI command inside the Docker container.
 *
 * @param list<string> $arguments wp subcommand arguments
 */
function runWpCli(string $container, string $wpPath, array $arguments): string
{
    return Shell\execute('docker', [
        'exec',
        $container,
        'gosu',
        'wordpress',
        'wp',
        '--path=' . $wpPath,
        ...$arguments,
    ], cancellation: new TimeoutCancellationToken(Duration::seconds(DOCKER_TIMEOUT)));
}

/**
 * Find a running WordPress Docker container.
 *
 * @param list<string> $names Container names to try.
 */
function findContainer(array $names = CONTAINER_NAMES): ?string
{
    $output = Shell\execute('docker', [
        'ps',
        '--format={{.Names}}',
    ], cancellation: new TimeoutCancellationToken(Duration::seconds(DOCKER_PS_TIMEOUT)));

    $running = Vec\filter(
        parseLines($output),
        static fn(string $name): bool => $name !== '',
    );

    foreach ($names as $name) {
        if (Iter\any($running, static fn(string $r): bool => $r === $name)) {
            return $name;
        }
    }
    return null;
}

/**
 * Split a multi-line string into non-empty trimmed lines.
 *
 * @return list<string>
 */
function parseLines(string $input): array
{
    return Vec\filter(
        Vec\map(
            Str\split(Str\trim($input), "\n"),
            Str\trim(...),
        ),
        static fn(string $line): bool => $line !== '',
    );
}

/**
 * Remove duplicates, template hooks ({$...}), trim, sort.
 *
 * @param list<string> $hooks
 * @return list<string>
 */
function normalizeHooks(array $hooks): array
{
    return Vec\sort(
        Vec\filter(
            Vec\unique($hooks),
            static fn(string $h): bool => !Str\contains($h, '{$'),
        ),
    );
}

/**
 * Find PHP files recursively, skipping vendor/node_modules.
 *
 * @return list<string>
 */
function findPhpFiles(string $dir): array
{
    $files = [];
    $it = new \RecursiveIteratorIterator(
        new \RecursiveDirectoryIterator($dir, \FilesystemIterator::SKIP_DOTS),
    );
    foreach ($it as $file) {
        /** @var \SplFileInfo $file */
        if (!$file->isFile() || $file->getExtension() !== 'php') {
            continue;
        }
        $path = $file->getPathname();
        if (Iter\any(SKIP_DIRS, static fn(string $d): bool => Str\contains($path, $d))) {
            continue;
        }
        $files[] = $path;
    }
    return $files;
}

// ── Render helpers ─────────────────────────────────────────────────────────

/**
 * Render a hook list as escaped, chunked, comma-separated lines.
 *
 * @param list<string> $hooks
 * @return list<string>
 */
function renderHookLines(array $hooks): array
{
    return Vec\map(
        Vec\chunk($hooks, CHUNK_SIZE),
        static fn(array $chunk): string => '        '
        . Str\join(
            Vec\map(
                $chunk,
                static fn(string $h): string => "'" . Str\replace($h, "'", "\\'") . "'",
            ),
            ', ',
        )
        . ',',
    );
}

/**
 * Build a single expectedArguments() block.
 *
 * @param list<string> $hooks
 */
function renderExpectedArguments(string $target, array $hooks): string
{
    $lines = renderHookLines($hooks);

    return "    expectedArguments(\n        {$target},\n        0,\n"
        . Str\join($lines, "\n") . "\n    );";
}

/**
 * @param list<string> $hooks
 */
function renderArgumentsSet(string $setName, array $hooks): string
{
    $lines = renderHookLines($hooks);

    return "    registerArgumentsSet('{$setName}',\n"
        . Str\join($lines, "\n") . "\n    );";
}

/**
 * Create a boilerplate .phpstorm.meta.php file.
 */
function createBoilerplate(): string
{
    return "<?php\nnamespace PHPSTORM_META {\n\n"
        . "    // === DO NOT EDIT BETWEEN THESE MARKERS — auto-generated by generate-meta-hooks ===\n"
        . "    // BEGIN-AUTO-GENERATED\n"
        . "    // END-AUTO-GENERATED\n"
        . "}\n";
}

/**
 * Render metadata blocks using registerArgumentsSet for DRY hook lists.
 *
 * @param list<string> $actions
 * @param list<string> $filters
 * @param list<string> $tags
 */
function renderMetadataSection(array $actions, array $filters, array $tags = []): string
{
    $result = '';
    $unit = 0;
    $listHooksAction = 'wp_hooks_actions';
    $listHooksFilter = 'wp_hooks_filters';
    $listHooksTags = 'wp_hooks_tags';

    // ── 1. registerArgumentsSet: actions ────────────────────────────────
    $unit++;
    $result .= "    // Unit #{$unit}: registerArgumentsSet — action hooks\n";
    $result .= renderArgumentsSet($listHooksAction, $actions) . "\n\n";

    // ── 2. registerArgumentsSet: filters ────────────────────────────────
    $unit++;
    $result .= "    // Unit #{$unit}: registerArgumentsSet — filter hooks\n";
    $result .= renderArgumentsSet($listHooksFilter, $filters) . "\n\n";

    // ── 3. registerArgumentsSet: tags (grouping metadata) ───────────────
    if ($tags !== []) {
        $unit++;
        $result .= "    // Unit #{$unit}: registerArgumentsSet — hook tags\n";
        $result .= renderArgumentsSet($listHooksTags, $tags) . "\n\n";
    }

    // ── 4. expectedArguments blocks referencing the sets ────────────────
    // Format: [Comment => [Target, ParamIndex, [ArgumentSets]]]
    $expectedBlocks = [
        'Action hooks for #[Action] attribute' => [
            '\\WPLokerBJM\\Core\\Container\\Attributes\\Action::__construct()',
            0,
            ["argumentsSet('{$listHooksAction}')"],
        ],
        'Filter hooks for #[Filter] attribute' => [
            '\\WPLokerBJM\\Core\\Container\\Attributes\\Filter::__construct()',
            0,
            ["argumentsSet('{$listHooksFilter}')"],
        ],
        'Hooks for \\do_action()' => [
            '\\do_action()',
            0,
            ["argumentsSet('{$listHooksAction}')"],
        ],
        'Hooks for \\apply_filters()' => [
            '\\apply_filters()',
            0,
            ["argumentsSet('{$listHooksFilter}')"],
        ],
        'Hooks for \\add_action()' => [
            '\\add_action()',
            0,
            ["argumentsSet('{$listHooksAction}')"],
        ],
        'Hooks for \\add_filter()' => [
            '\\add_filter()',
            0,
            ["argumentsSet('{$listHooksFilter}')"],
        ],
        'List hooks (deferred) to register' => [
            '\\WPLokerBJM\\Core\\Container\\Support\\WPHooks\\WPHooksContainerRegistry::activateDeferredByHook()',
            0,
            ["argumentsSet('{$listHooksAction}')", "argumentsSet('{$listHooksFilter}')"],
        ],
        'List hooks to unregister' => [
            '\\WPLokerBJM\\Core\\Container\\Support\\WPHooks\\WPHooksContainerRegistry::unregisterByHook()',
            0,
            ["argumentsSet('{$listHooksAction}')", "argumentsSet('{$listHooksFilter}')"],
        ],
        'List hooks (deferred) to unregister' => [
            '\\WPLokerBJM\\Core\\Container\\Support\\WPHooks\\WPHooksContainerRegistry::unregisterDeferredByHook()',
            0,
            ["argumentsSet('{$listHooksAction}')", "argumentsSet('{$listHooksFilter}')"],
        ],
    ];

    if ($tags !== []) {
        $expectedBlocks += [
            // Single String Autocomplete for $tag (index 5)
            'Tag hooks for #[Action] attribute' => [
                '\\WPLokerBJM\\Core\\Container\\Attributes\\Action::__construct()',
                5,
                ["argumentsSet('{$listHooksTags}')"],
            ],
            'Tag hooks for #[Filter] attribute' => [
                '\\WPLokerBJM\\Core\\Container\\Attributes\\Filter::__construct()',
                5,
                ["argumentsSet('{$listHooksTags}')"],
            ],
            // Array Element Autocomplete for $tag (tag: ['...'])
            'Tag array elements for #[Action] attribute' => [
                'elementType(\\WPLokerBJM\\Core\\Container\\Attributes\\Action::__construct(), 5)',
                0,
                ["argumentsSet('{$listHooksTags}')"],
            ],
            'Tag array elements for #[Filter] attribute' => [
                'elementType(\\WPLokerBJM\\Core\\Container\\Attributes\\Filter::__construct(), 5)',
                0,
                ["argumentsSet('{$listHooksTags}')"],
            ],
            'Hook tags (deferred) to activate' => [
                '\\WPLokerBJM\\Core\\Container\\Support\\WPHooks\\WPHooksContainerRegistry::activateDeferredByTags()',
                0,
                ["argumentsSet('{$listHooksTags}')"],
            ],
            'Hook tags to unregister' => [
                '\\WPLokerBJM\\Core\\Container\\Support\\WPHooks\\WPHooksContainerRegistry::unregisterByTags()',
                0,
                ["argumentsSet('{$listHooksTags}')"],
            ],
            'Hook tags (deferred) to unregister' => [
                '\\WPLokerBJM\\Core\\Container\\Support\\WPHooks\\WPHooksContainerRegistry::unregisterDeferredByTags()',
                0,
                ["argumentsSet('{$listHooksTags}')"],
            ],
        ];
    }

    foreach ($expectedBlocks as $comment => [$target, $paramIndex, $args]) {
        $unit++;
        $renderedArgs = Str\join($args, ",\n        ");
        $result .= "    // Unit #{$unit}: {$comment}\n";
        $result .= "    expectedArguments(\n        {$target},\n        {$paramIndex},\n        {$renderedArgs},\n    );\n\n";
    }

    return Str\trim_right($result, "\n");
}

/**
 * Replace the section between markers with new generated content.
 */
function replaceGeneratedSection(string $content, string $generated): string
{
    $startPos = Str\search($content, MARKER_BEGIN);
    $endPos = Str\search($content, MARKER_END);

    if ($startPos === null || $endPos === null || $startPos >= $endPos) {
        throw new \RuntimeException('Markers not found in ' . MARKER_BEGIN . ' / ' . MARKER_END);
    }

    $before = Str\slice($content, 0, $startPos + Str\length(MARKER_BEGIN));
    $after = Str\slice($content, $endPos);
    return $before . "\n" . $generated . "\n    " . $after;
}

